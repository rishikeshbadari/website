import { readFile, readdir, writeFile, unlink } from 'node:fs/promises';
import { marked } from 'marked';
import { parseOrder, sortEssays } from './essay-order.mjs';

const generated = '<!-- Generated by scripts/build-essays.mjs. Edit essays/*.md instead. -->';
const escape = text => text.replace(/[&<>"']/g, char => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
}[char]));

function page(title, content, detail = false) {
    const prefix = detail ? '../' : '';
    return `<!DOCTYPE html>
${generated}
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <meta name="color-scheme" content="light">
    <title>${escape(title)} — Rishikesh Badari</title>
    <meta name="description" content="${escape(title)} — essays by Rishikesh Badari.">
    <meta property="og:title" content="${escape(title)} — Rishikesh Badari">
    <meta property="og:type" content="${detail ? 'article' : 'website'}">
    <meta name="theme-color" content="#faf9f6">
    <link rel="stylesheet" href="${prefix}css/site.css">
</head>
<body>
    <a class="skip-link" href="#main">Skip to content</a>
    <header class="site-header">
        <nav aria-label="Main navigation">
            <a href="${prefix}index.html">Home</a>
            <a href="${prefix}projects.html">Projects</a>
            <a href="${prefix}pictures.html">Pictures</a>
            <a href="${prefix}essays.html" aria-current="${detail ? 'location' : 'page'}">Essays</a>
        </nav>
    </header>
    <main id="main">
${content}
    </main>
    <footer class="site-footer">
        <a href="mailto:badari.rishikesh@gmail.com">Email</a>
        <a href="https://www.linkedin.com/in/rbadari/">LinkedIn</a>
        <a href="https://github.com/rishikeshbadari">GitHub</a>
    </footer>
</body>
</html>
`;
}

export function essayTitle(markdown, filename) {
    // Parse Markdown so headings in code blocks are not mistaken for titles.
    const heading = marked.lexer(markdown.replace(/^\uFEFF/, ''))
        .find(token => token.type === 'heading' && token.depth === 1);
    if (heading?.text.trim()) return heading.text.trim();
    return filename.replace(/\.md$/, '').split('-')
        .map(word => word.charAt(0).toUpperCase() + word.slice(1)).join(' ');
}

export async function buildEssays() {
    const folder = new URL('../essays/', import.meta.url);
    const files = await readdir(folder);
    const essays = await Promise.all(files.filter(file => file.endsWith('.md')).map(async file => {
        if (!/^[a-z0-9]+(?:-[a-z0-9]+)*\.md$/.test(file)) {
            throw new Error('Essay filenames must use lowercase letters, numbers, and hyphens: ' + file);
        }
        const markdown = await readFile(new URL(file, folder), 'utf8');
        const title = essayTitle(markdown, file);
        return { title, filename: file.replace(/\.md$/, '.html'), html: marked.parse(markdown) };
    }));
    let order = [];
    try {
        order = parseOrder(await readFile(new URL('order.txt', folder), 'utf8'));
    } catch (error) {
        if (error.code !== 'ENOENT') throw error;
    }
    sortEssays(essays, order);

    // Never overwrite a manually authored page that happens to share a name.
    for (const essay of essays) {
        if (files.includes(essay.filename)) {
            const existing = await readFile(new URL(essay.filename, folder), 'utf8');
            if (!existing.includes(generated)) throw new Error('Existing non-generated essay page: ' + essay.filename);
        }
    }
    for (const essay of essays) {
        const content = '        <p><a href="../essays.html">← Back</a></p>\n' +
            '        <article class="essay-content">\n' + essay.html.trim() +
            '\n        </article>';
        await writeFile(new URL(essay.filename, folder), page(essay.title, content, true));
    }
    const links = essays.map(essay =>
        '            <li><a href="essays/' + essay.filename + '">' + escape(essay.title) + '</a></li>').join('\n');
    const listing = essays.length ? '        <ul class="essay-list" aria-label="Essays">\n' + links + '\n        </ul>' :
        '        <p>No essays yet.</p>';
    const introduction = marked.parse(await readFile(new URL('../content/essays.md', import.meta.url), 'utf8')).trim();
    const introBlock = introduction ? '        <div class="essay-content essay-intro">\n' +
        introduction.split('\n').map(line => '            ' + line).join('\n') + '\n        </div>\n' : '';
    await writeFile(new URL('../essays.html', import.meta.url), page('Essays', introBlock + listing));

    // Remove only generated output whose Markdown source has been removed.
    for (const file of files.filter(file => file.endsWith('.html'))) {
        if (essays.some(essay => essay.filename === file)) continue;
        if ((await readFile(new URL(file, folder), 'utf8')).includes(generated)) {
            await unlink(new URL(file, folder));
        }
    }
    console.log('Built ' + essays.length + ' essay pages and essays.html.');
}
